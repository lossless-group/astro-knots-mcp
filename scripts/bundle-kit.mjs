// Bundle skills/ into the Worker as worker/kit.generated.ts, so the skills the
// link MCP serves ship with every deploy and match the plugins exactly (the
// same pattern as event-hog). Text files only. Runs from wrangler's build
// command and before tests.

import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { extname, join, relative, sep } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const TEXT = new Set([".md", ".txt", ".json", ".yaml", ".yml", ".sh", ".py", ".ts", ".mjs", ".js", ".css", ".astro", ".svelte", ".toml"]);

function walk(dir) {
  return readdirSync(dir).flatMap((name) => {
    if (name === ".DS_Store") return [];
    const full = join(dir, name);
    return statSync(full).isDirectory() ? walk(full) : [full];
  });
}

const files = {};
for (const full of walk(join(root, "skills")).sort()) {
  if (!TEXT.has(extname(full))) continue;
  files[relative(root, full).split(sep).join("/")] = readFileSync(full, "utf8");
}

writeFileSync(
  join(root, "worker", "kit.generated.ts"),
  `// Generated by scripts/bundle-kit.mjs from skills/. Don't edit; edit skills/ and rebuild.\n` +
    `export const KIT: Record<string, string> = ${JSON.stringify(files, null, 1)};\n`,
);
console.log(`bundle-kit: ${Object.keys(files).length} files from skills/`);
